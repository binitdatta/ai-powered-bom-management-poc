"""
app/excel/builder.py  —  openpyxl Excel workbook generation
Produces a multi-tab workbook from BOM validation data.
"""
import os
import uuid
from datetime import datetime
from typing import Optional
import openpyxl
from openpyxl.styles import (Font, PatternFill, Alignment,
                              Border, Side, numbers)
from openpyxl.utils import get_column_letter
from config import settings

# Colours
BLUE_DARK   = "1A3A6E"
BLUE_MID    = "2563C7"
BLUE_LIGHT  = "DBEAFE"
GREEN_LIGHT = "DCFCE7"
RED_LIGHT   = "FEE2E2"
YELLOW_LIGHT= "FEF9C3"
GREY_LIGHT  = "F1F5F9"
WHITE       = "FFFFFF"


def _hdr(ws, row: int, col: int, value, bold=True, bg=BLUE_DARK, fg=WHITE, wrap=False):
    cell = ws.cell(row=row, column=col, value=value)
    cell.font      = Font(bold=bold, color=fg, size=10)
    cell.fill      = PatternFill("solid", fgColor=bg)
    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=wrap)
    return cell


def _cell(ws, row, col, value, bg=None, bold=False, fmt=None):
    cell = ws.cell(row=row, column=col, value=value)
    cell.font      = Font(bold=bold, size=10)
    cell.alignment = Alignment(vertical="center", wrap_text=False)
    if bg:
        cell.fill  = PatternFill("solid", fgColor=bg)
    if fmt:
        cell.number_format = fmt
    return cell


def _auto_width(ws):
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            if cell.value:
                max_len = max(max_len, len(str(cell.value)))
        ws.column_dimensions[col_letter].width = min(max(max_len + 2, 10), 50)


def _thin_border():
    side = Side(style="thin", color="CBD5E1")
    return Border(left=side, right=side, top=side, bottom=side)


